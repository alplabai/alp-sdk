/* INA236 conversion timing.  16 averaged conversions of 140 us shunt + 140 us
 * bus = 4.48 ms per reported sample (the driver computes this from the
 * datasheet tables; we only pick the codes).  Two reasons for this pick:
 *   - Rate: 4.48 ms per conversion sits an order of magnitude above the ~0.5 ms
 *     an I2C register read costs at 100 kHz, so the sampler is never the
 *     bottleneck and never aliases.
 *   - Window: 250 samples then spans ~1.12 s, comfortably long enough that the
 *     ~4.5 ms of averaging that straddles each window boundary is a ~0.4 %
 *     edge effect rather than a real error.
 * Averaging is free accuracy here: energy is the integral of power, and the
 * hardware average preserves the mean it integrates. */
static constexpr ina236_avg_t  SAMPLE_AVG    = INA236_AVG_16;
static constexpr ina236_ct_t   SAMPLE_VBUSCT = INA236_CT_140US;
static constexpr ina236_ct_t   SAMPLE_VSHCT  = INA236_CT_140US;
static constexpr ina236_mode_t SAMPLE_MODE   = INA236_MODE_SHUNT_BUS_CONT;

/* Samples per window.  The default is sized against
 * CONFIG_RAM_CONSOLE_BUFFER_SIZE: this many samples x 2 phases x WINDOW_PAIRS
 * lines must fit, or the capture truncates mid-window -- which would look like
 * a shorter (but valid) window and yield a quietly wrong energy figure instead
 * of an obvious failure.
 *
 * Override for the WHOLE-BOARD CROSS-CHECK build.  Validating this measurement
 * against the bench PSU's input power needs windows long enough for a slow
 * external instrument to resolve each phase (tens of seconds, not one), which
 * is far more samples than the console can carry.  So pair a long window with
 * -DAEN_ENERGY_EMIT_SAMPLES=0: the energy is integrated incrementally as
 * samples arrive, so window length is bounded by the measurement, not by the
 * buffer.  That build reports only the summary lines and is NOT parseable by
 * the host re-integrator -- which is the honest outcome, since there is no
 * sample stream for it to re-integrate.
 *
 *   -DAEN_ENERGY_SAMPLES_PER_WINDOW=6000 -DAEN_ENERGY_WINDOW_PAIRS=1 \
 *   -DAEN_ENERGY_EMIT_SAMPLES=0            (~26.9 s per phase) */
#ifndef AEN_ENERGY_SAMPLES_PER_WINDOW
#define AEN_ENERGY_SAMPLES_PER_WINDOW 250
#endif
#ifndef AEN_ENERGY_WINDOW_PAIRS
#define AEN_ENERGY_WINDOW_PAIRS 3
#endif
#ifndef AEN_ENERGY_EMIT_SAMPLES
#define AEN_ENERGY_EMIT_SAMPLES 1
#endif

static constexpr size_t SAMPLES_PER_WINDOW = AEN_ENERGY_SAMPLES_PER_WINDOW;

/* Repeated (active, idle) pairs.  Three is the minimum that yields a spread
 * (a sample standard deviation) rather than a bare single number. */
static constexpr size_t WINDOW_PAIRS = AEN_ENERGY_WINDOW_PAIRS;

/* Per-sample buffering exists ONLY to replay the stream on the console after a
 * window closes; the energy itself is accumulated as samples arrive.  With
 * emission off the buffer collapses to nothing. */
static constexpr bool   EMIT_SAMPLES = (AEN_ENERGY_EMIT_SAMPLES != 0);
static constexpr size_t SAMPLE_BUF   = EMIT_SAMPLES ? SAMPLES_PER_WINDOW : 1;

/* Samples per rail during the scan -- just enough to rank six rails by how much
 * their shunt voltage moves, not to measure any of them accurately. */
static constexpr size_t SCAN_SAMPLES = 16;

/* Switch to the finer +/-20.48 mV ADC range only if the largest shunt magnitude
 * seen during the scan stays below this, leaving ~25 % headroom for peaks the
 * short scan did not catch.  Above it, clipping is the worse error. */
static constexpr int32_t ADCRANGE_20MV_MAX_UV = 15000;

/* ------------------------------------------------------------------------- *
 * Cycle counter.
 *
 * The DWT cycle counter is the finest clock on this core: it ticks once per CPU
 * cycle (160 MHz here => 6.25 ns).  It is optional in the architecture, so
 * DWT_CTRL.NOCYCCNT is checked and Zephyr's k_cycle_get_32() is used instead
 * when the hardware does not implement it -- silently timestamping every sample
 * with a frozen zero would turn every duration into nonsense.
 *
 * Both sources are read as a raw uint32 that WRAPS (every ~26.8 s at 160 MHz).
 * Every consumer takes unsigned differences, which stay correct across a single
 * wrap, and the host is handed the raw counts plus a millisecond cross-check per
 * window so it can verify the cycles-per-second figure rather than trust it.
 * ------------------------------------------------------------------------- */

static bool g_dwt_in_use;

static void cycles_init(void)
{
	/* TRCENA gates the whole trace/debug block, DWT included. */
	DCB->DEMCR |= DCB_DEMCR_TRCENA_Msk;
	__DSB();
	if (DWT->CTRL & DWT_CTRL_NOCYCCNT_Msk) {
		g_dwt_in_use = false; /* not implemented -- fall back */
		return;
	}
	DWT->CYCCNT = 0U;
	DWT->CTRL |= DWT_CTRL_CYCCNTENA_Msk;
	__DSB();
	/* Prove it actually advances before trusting it: a counter that reads
	 * back frozen despite CYCCNTENA (a locked or gated debug block) must fall
	 * back too, not be believed. */
	uint32_t a = DWT->CYCCNT;
	__NOP();
	__NOP();
	__NOP();
	g_dwt_in_use = (DWT->CYCCNT != a);
}

static inline uint32_t cycles_now(void)
{
	return g_dwt_in_use ? DWT->CYCCNT : k_cycle_get_32();
}

/* Cycles per second for whichever source is live.  Both count CPU cycles on
 * this core, so both scale by the kernel's configured cycle rate. */
static inline uint32_t cycles_per_s(void)
{
	return sys_clock_hw_cycles_per_sec();
}

