/* ------------------------------------------------------------------------- *
 * Sample buffer -- one window at a time, emitted after the window closes.
 *
 * Printing during a window would corrupt the very thing being measured: the
 * console write costs time and energy inside the integration interval.  So
 * samples are buffered in DTCM and flushed between windows.
 * ------------------------------------------------------------------------- */
struct sample_t {
	uint32_t cycles;
	uint16_t power_raw;
};
static sample_t g_window[SAMPLE_BUF];

enum phase_t { PHASE_IDLE = 0, PHASE_ACTIVE = 1 };

static const char *phase_name(phase_t p)
{
	return (p == PHASE_ACTIVE) ? "active" : "idle";
}

/* Latched evidence, readable by symbol over SWD even with no console. */
volatile int      g_rail_index    = -1;
volatile int      g_alloc_status  = -1;
volatile int      g_invoke_status = -1;
volatile uint32_t g_total_inferences;
volatile float    g_mj_per_inference;

/* ------------------------------------------------------------------------- *
 * One window.
 *
 * Both phases run the SAME loop with the SAME polling cadence, and differ only
 * in what they do between polls: run an inference, or spin.  That symmetry is
 * what makes the sampler's own cost cancel in the active-minus-idle
 * subtraction -- if the idle window polled at a different rate, its I2C traffic
 * would not cancel and the difference would carry the sampler's energy too.
 *
 * Returns the number of inferences completed (0 for an idle window).
 * ------------------------------------------------------------------------- */
struct window_result {
	uint32_t inferences;  /* completed inferences (0 for an idle window)   */
	size_t   samples;     /* conversions actually captured                */
	size_t   buffered;    /* of those, how many were kept for emission    */
	float    energy_mj;   /* trapezoidal integral, accumulated in-flight  */
	uint32_t i2c_errors;  /* failed conversion-ready / power reads         */
	uint32_t span_cycles; /* window duration, cycle counter               */
	uint32_t span_ms;     /* same window, kernel millisecond clock        */
	bool     timed_out;   /* deadline hit before `cap` samples arrived     */
	int      last_rc;     /* last non-OK driver status, ALP_OK if none     */
};

/* How long a window may overrun its predicted duration before it is abandoned.
 * A sampling loop gated on a hardware flag must never be able to spin forever:
 * if the monitor stops producing conversions -- a wedged bus, a device knocked
 * out of continuous mode -- an unbounded loop turns into a silent hang, and the
 * only evidence left is a truncated console that looks like a crash.  With a
 * deadline the same failure becomes a reported short window, which the operator
 * can act on and the host can reject. */
static constexpr uint32_t WINDOW_DEADLINE_MULT = 4U;

static void run_window(ina236_t                 *mon,
                       tflite::MicroInterpreter *interp,
                       phase_t                   phase,
                       uint32_t                  poll_cycles,
                       size_t                    cap,
                       uint32_t                  deadline_ms,
                       float                     power_lsb_w,
                       float                     cyc_per_s,
                       window_result            *out)
{
	uint32_t inferences = 0;
	size_t   got        = 0;
	uint32_t errs       = 0;
	int      last_rc    = ALP_OK;
	bool     timed_out  = false;
	float    energy_j   = 0.0f;
	uint32_t prev_c     = 0;
	uint16_t prev_raw   = 0;

	uint32_t t_start_c  = cycles_now();
	int64_t  t_start_ms = k_uptime_get();
	uint32_t next_poll  = t_start_c + poll_cycles;

	while (got < cap) {
		/* The deadline uses the kernel's 64-bit millisecond clock, NOT the
		 * cycle counter, for two reasons: a long-window build's allowance
		 * exceeds what a 32-bit cycle count can express at 160 MHz (it wraps
		 * every ~26.8 s), and the millisecond clock keeps running when a
		 * debugger owns the trace block. */
		if ((uint32_t)(k_uptime_get() - t_start_ms) > deadline_ms) {
			timed_out = true;
			break;
		}
		/* Signed comparison of the unsigned difference: correct across a
		 * counter wrap, unlike a plain `now >= next_poll`. */
		if ((int32_t)(cycles_now() - next_poll) >= 0) {
			next_poll += poll_cycles;
			/* An inference can overrun a poll slot; resynchronise rather
			 * than burning through a backlog of missed deadlines. */
			if ((int32_t)(cycles_now() - next_poll) >= 0) {
				next_poll = cycles_now() + poll_cycles;
			}
			bool         ready = false;
			alp_status_t rc    = ina236_conversion_ready(mon, &ready);
			if (rc != ALP_OK) {
				errs++;
				last_rc = (int)rc;
			} else if (ready) {
				uint16_t raw = 0;
				rc           = ina236_read_power_raw(mon, &raw);
				if (rc != ALP_OK) {
					errs++;
					last_rc = (int)rc;
				} else {
					/* Timestamp the read, not the loop top: the
					 * trapezoid integrates against real intervals,
					 * so honest timestamps absorb poll jitter. */
					uint32_t c = cycles_now();
					/* Accumulate the trapezoid as samples arrive, so
					 * window length is set by the measurement rather
					 * than by how many samples fit in RAM. */
					if (got > 0 && cyc_per_s > 0.0f) {
						float dt = (float)(c - prev_c) / cyc_per_s;
						float p0 = (float)prev_raw * power_lsb_w;
						float p1 = (float)raw * power_lsb_w;
						energy_j += 0.5f * (p0 + p1) * dt;
					}
					prev_c   = c;
					prev_raw = raw;
					if (EMIT_SAMPLES && got < SAMPLE_BUF) {
						g_window[got].cycles    = c;
						g_window[got].power_raw = raw;
					}
					got++;
				}
			}
		} else if (phase == PHASE_ACTIVE) {
			TfLiteStatus st = interp->Invoke();
			g_invoke_status = (int)st;
			if (st != kTfLiteOk) {
				break; /* a failing invoke must not be averaged in */
			}
			inferences++;
		}
		/* PHASE_IDLE between polls: spin.  See the baseline note in the file
		 * header -- this is a CPU-spin/NPU-quiet baseline, not WFI. */
	}

	out->inferences  = inferences;
	out->samples     = got;
	out->buffered    = (EMIT_SAMPLES && got < SAMPLE_BUF) ? got : (EMIT_SAMPLES ? SAMPLE_BUF : 0);
	out->energy_mj   = energy_j * 1000.0f;
	out->i2c_errors  = errs;
	out->span_cycles = cycles_now() - t_start_c;
	out->span_ms     = (uint32_t)(k_uptime_get() - t_start_ms);
	out->timed_out   = timed_out;
	out->last_rc     = last_rc;
}

/* Emit one window's samples plus its span.  The host re-integrates from these
 * raw counts; the ENERGY-W line's millisecond span is an independent clock so
 * the host can confirm the cycles-per-second figure instead of trusting it. */
static void emit_window(size_t idx, phase_t phase, const window_result &w)
{
	uint32_t base = (w.buffered > 0) ? g_window[0].cycles : 0U;
	for (size_t i = 0; i < w.buffered; i++) {
		printk("ENERGY-S %u %s %u %u\n",
		       (unsigned)idx,
		       phase_name(phase),
		       (unsigned)(g_window[i].cycles - base),
		       (unsigned)g_window[i].power_raw);
	}
	printk("ENERGY-W %u %s %u %u %u\n",
	       (unsigned)idx,
	       phase_name(phase),
	       (unsigned)w.samples,
	       (unsigned)w.span_cycles,
	       (unsigned)w.span_ms);
	/* Say so when the printed stream is shorter than what was integrated, so a
	 * host re-integrating the stream cannot mistake a partial replay for the
	 * whole window and silently report a fraction of the real energy. */
	if (w.buffered != w.samples) {
		printk("ENERGY-WPART %u %s emitted=%u of %u samples (device integral is "
		       "authoritative for this build)\n",
		       (unsigned)idx,
		       phase_name(phase),
		       (unsigned)w.buffered,
		       (unsigned)w.samples);
	}
	/* Only when something went wrong -- a clean run stays quiet so the
	 * diagnostic line means what it says. */
	if (w.timed_out || w.i2c_errors > 0) {
		printk("ENERGY-WERR %u %s timed_out=%d i2c_errors=%u last_rc=%d got=%u/%u\n",
		       (unsigned)idx,
		       phase_name(phase),
		       (int)w.timed_out,
		       (unsigned)w.i2c_errors,
		       w.last_rc,
		       (unsigned)w.samples,
		       (unsigned)SAMPLES_PER_WINDOW);
	}
}

/* Mean AND spread of the shunt voltage over a short burst.
 *
 * The spread is not decoration: ranking six rails by a raw difference of means
 * picks whichever rail's noise happened to move most, which on this bench chose
 * a 0.6 mA housekeeping rail over the 93 mA compute rail.  The standard error
 * derived from `sd_out` is what lets the caller tell a real load step from
 * dither in the last ADC count. */
static void scan_shunt_stats(ina236_t                 *mon,
                             tflite::MicroInterpreter *interp,
                             phase_t                   phase,
                             uint32_t                  poll_cycles,
                             int32_t                  *mean_out,
                             int32_t                  *sd_out)
{
	int64_t  sum       = 0;
	int64_t  sum_sq    = 0;
	size_t   got       = 0;
	uint32_t next_poll = cycles_now() + poll_cycles;

	while (got < SCAN_SAMPLES) {
		if ((int32_t)(cycles_now() - next_poll) >= 0) {
			next_poll  = cycles_now() + poll_cycles;
			bool ready = false;
			if (ina236_conversion_ready(mon, &ready) == ALP_OK && ready) {
				int32_t uv = 0;
				if (ina236_read_shunt_uv(mon, &uv) == ALP_OK) {
					sum += uv;
					sum_sq += (int64_t)uv * (int64_t)uv;
					got++;
				}
			}
		} else if (phase == PHASE_ACTIVE) {
			(void)interp->Invoke();
		}
	}
	int64_t n    = (int64_t)SCAN_SAMPLES;
	int64_t mean = sum / n;
	/* Population variance is enough to size a noise floor; the sample-vs-
	 * population distinction is far below the effect we are gating on. */
	int64_t var = (sum_sq / n) - (mean * mean);
	if (var < 0) var = 0;
	*mean_out = (int32_t)mean;
	*sd_out   = (int32_t)__builtin_sqrtf((float)var);
}

static inline int32_t abs32(int32_t v)
{
	return v < 0 ? -v : v;
}

int main(void)
{
	printk("\n=== aen-inference-energy ===\n");
	printk("model      : %s (%u bytes)\n", NETWORK_MODEL_NAME, (unsigned)NETWORK_MODEL_LEN);

	cycles_init();
	const uint32_t cps = cycles_per_s();
	printk("clock      : %u Hz, timestamp source %s\n",
	       (unsigned)cps,
	       g_dwt_in_use ? "DWT CYCCNT" : "k_cycle_get_32 (DWT NOCYCCNT)");

	const struct device *npu       = DEVICE_DT_GET(NPU_NODE);
	bool                 npu_ready = device_is_ready(npu);
	printk(
	    "npu ready  : %d (Ethos-U85 @0x%08x)\n", (int)npu_ready, (unsigned)DT_REG_ADDR(NPU_NODE));

	/* --- Bring up the model once ------------------------------------------
	 * Built ONCE, invoked many times.  Rebuilding the interpreter per
	 * iteration would fold model parsing and tensor allocation into the
	 * measured window, and the reported cost per "inference" would then
	 * include work a real application does exactly once. */
	memcpy(model_sram, networkModelData, NETWORK_MODEL_LEN);

	const tflite::Model *model = tflite::GetModel(model_sram);
	if (model->version() != TFLITE_SCHEMA_VERSION) {
		printk("RESULT FAIL: model schema %u != supported %d\n",
		       (unsigned)model->version(),
		       TFLITE_SCHEMA_VERSION);
		return 0;
	}

	tflite::MicroMutableOpResolver<8> resolver;
	resolver.AddEthosU();
	resolver.AddReshape();
	resolver.AddConv2D();
	resolver.AddDepthwiseConv2D();
	resolver.AddFullyConnected();
	resolver.AddSoftmax();
	resolver.AddQuantize();
	resolver.AddDequantize();

	tflite::MicroInterpreter interpreter(model, resolver, tensor_arena, TENSOR_ARENA_SIZE);
	TfLiteStatus             alloc = interpreter.AllocateTensors();
	g_alloc_status                 = (int)alloc;
	if (alloc != kTfLiteOk) {
		printk("RESULT FAIL: AllocateTensors=%d\n", (int)alloc);
		return 0;
	}
	TfLiteTensor *input = interpreter.input(0);
	memset(input->data.raw, 0, input->bytes);

	/* One warm-up invoke, outside every window: the first call through the
	 * Ethos-U driver reserves the device and faults in code paths a steady
	 * state never repeats, and folding that into window 0 would inflate it. */
	TfLiteStatus warm = interpreter.Invoke();
	g_invoke_status   = (int)warm;
	if (warm != kTfLiteOk) {
		printk("RESULT FAIL: warm-up Invoke=%d (NPU dispatch failed) npu_ready=%d\n",
		       (int)warm,
		       (int)npu_ready);
		return 0;
	}
	printk("inference  : warm-up OK (input %u B, output %u B)\n",
	       (unsigned)input->bytes,
	       (unsigned)interpreter.output(0)->bytes);

	/* --- Open the rail-monitor bus --------------------------------------- */
	alp_i2c_config_t i2c_cfg = ALP_I2C_CONFIG_DEFAULT(EVK_I2C_BUS_SENSORS);
	alp_i2c_t       *bus     = alp_i2c_open(&i2c_cfg);
	if (bus == NULL) {
		printk("RESULT FAIL: alp_i2c_open(EVK_I2C_BUS_SENSORS) returned NULL\n");
		return 0;
	}

	const uint32_t period_us =
	    ina236_sample_period_us(SAMPLE_AVG, SAMPLE_VBUSCT, SAMPLE_VSHCT, SAMPLE_MODE);
	if (period_us == 0U) {
		printk("RESULT FAIL: sample period 0 (shutdown mode selected)\n");
		return 0;
	}
	/* Poll four times per conversion so a completed conversion is picked up
	 * within a quarter period; the recorded timestamp is the real read time,
	 * so the residual jitter does not bias the integral. */
	const uint32_t poll_cycles = (uint32_t)(((uint64_t)period_us * cps) / 4000000ULL);

	/* --- Scan: which rail actually feeds the compute? ---------------------
	 * Every rail is measured the same way and ranked by how far its shunt
	 * voltage moves between inferring and quiet.  An absent monitor simply
	 * does not compete. */
	printk("scan       : %u rails, %u samples/phase, period %u us\n",
	       (unsigned)ARRAY_SIZE(RAILS),
	       (unsigned)SCAN_SAMPLES,
	       (unsigned)period_us);

	/* Two independent rankings are kept, because the delta ranking is only
	 * trustworthy when SOME rail actually shows a significant step.
	 *   best_sig     -- largest significant (>= NOISE_SIGMA standard errors,
	 *                   and positive: active must draw MORE) delta.
	 *   best_current -- largest steady-state current, i.e. the rail carrying
	 *                   the most power regardless of whether this workload
	 *                   moves it.  The fallback, and reported as such.
	 * A tiny model genuinely produces no significant delta on any rail; in
	 * that case picking "the rail whose noise moved most" is worse than
	 * useless, because the resulting energy figure looks real. */
	static constexpr float NOISE_SIGMA = 3.0f;

	int     best_sig       = -1;
	int32_t best_sig_delta = 0;
	int32_t best_sig_peak  = 0;
	int     best_current   = -1;
	int32_t best_cur_uv    = 0;
	int32_t best_cur_peak  = 0;

	for (size_t i = 0; i < ARRAY_SIZE(RAILS); i++) {
		ina236_t     probe;
		alp_status_t rc = ina236_init(
		    &probe, bus, RAILS[i].addr, RAILS[i].shunt_ohms, RAILS[i].max_a, INA236_ADCRANGE_81MV);
		if (rc != ALP_OK) {
			printk("ENERGY-SCAN %-6s 0x%02x absent rc=%d\n", RAILS[i].name, RAILS[i].addr, (int)rc);
			continue;
		}
		if (ina236_configure(&probe, SAMPLE_AVG, SAMPLE_VBUSCT, SAMPLE_VSHCT, SAMPLE_MODE) !=
		    ALP_OK) {
			printk("ENERGY-SCAN %-6s 0x%02x configure failed\n", RAILS[i].name, RAILS[i].addr);
			continue;
		}
		/* Discard the conversions in flight across the reconfiguration --
		 * they average over both the old and new settings. */
		k_msleep((int32_t)(2U * period_us / 1000U) + 2);

		int32_t act = 0, act_sd = 0, idl = 0, idl_sd = 0;
		scan_shunt_stats(&probe, &interpreter, PHASE_ACTIVE, poll_cycles, &act, &act_sd);
		scan_shunt_stats(&probe, &interpreter, PHASE_IDLE, poll_cycles, &idl, &idl_sd);
		int32_t d    = act - idl;
		int32_t peak = abs32(act) > abs32(idl) ? abs32(act) : abs32(idl);

		/* Standard error of the difference of two means of SCAN_SAMPLES each. */
		float se = __builtin_sqrtf(((float)act_sd * (float)act_sd + (float)idl_sd * (float)idl_sd) /
		                           (float)SCAN_SAMPLES);
		bool  significant = (d > 0) && ((float)d > NOISE_SIGMA * se);

		printk("ENERGY-SCAN %-6s 0x%02x active_uv=%d(sd=%d) idle_uv=%d(sd=%d) "
		       "delta_uv=%d se_uv=%f significant=%d\n",
		       RAILS[i].name,
		       RAILS[i].addr,
		       (int)act,
		       (int)act_sd,
		       (int)idl,
		       (int)idl_sd,
		       (int)d,
		       (double)se,
		       (int)significant);

		if (significant && (best_sig < 0 || d > best_sig_delta)) {
			best_sig       = (int)i;
			best_sig_delta = d;
			best_sig_peak  = peak;
		}
		if (best_current < 0 || abs32(act) > abs32(best_cur_uv)) {
			best_current  = (int)i;
			best_cur_uv   = act;
			best_cur_peak = peak;
		}
		ina236_deinit(&probe);
	}

	if (best_current < 0) {
		printk("RESULT FAIL: no INA236 answered on EVK_I2C_BUS_SENSORS\n");
		return 0;
	}

	int         best       = (best_sig >= 0) ? best_sig : best_current;
	int32_t     best_delta = (best_sig >= 0) ? best_sig_delta : 0;
	int32_t     best_peak  = (best_sig >= 0) ? best_sig_peak : best_cur_peak;
	const char *criterion  = (best_sig >= 0) ? "largest-significant-delta" : "largest-current";

	/* Operator override: pin a specific monitor by 7-bit address, e.g.
	 * -DAEN_ENERGY_RAIL_ADDR=0x4A.  The automatic pick is right when a
	 * workload moves a rail measurably; when it does not, the person who
	 * knows which rail feeds the module should be able to say so without
	 * editing this file. */
#ifdef AEN_ENERGY_RAIL_ADDR
	for (size_t i = 0; i < ARRAY_SIZE(RAILS); i++) {
		if (RAILS[i].addr == (uint8_t)(AEN_ENERGY_RAIL_ADDR)) {
			best      = (int)i;
			criterion = "operator-override";
			break;
		}
	}
#endif
	g_rail_index = best;

	/* --- Range pick, from what the scan actually saw --------------------- */
	ina236_adcrange_t range =
	    (best_peak < ADCRANGE_20MV_MAX_UV) ? INA236_ADCRANGE_20MV : INA236_ADCRANGE_81MV;
	printk("rail       : %s @0x%02x by %s delta_uv=%d peak_uv=%d -> ADCRANGE %s\n",
	       RAILS[best].name,
	       RAILS[best].addr,
	       criterion,
	       (int)best_delta,
	       (int)best_peak,
	       range == INA236_ADCRANGE_20MV ? "20.48mV" : "81.92mV");

	ina236_t mon;
	if (ina236_init(
	        &mon, bus, RAILS[best].addr, RAILS[best].shunt_ohms, RAILS[best].max_a, range) !=
	        ALP_OK ||
	    ina236_configure(&mon, SAMPLE_AVG, SAMPLE_VBUSCT, SAMPLE_VSHCT, SAMPLE_MODE) != ALP_OK) {
		printk("RESULT FAIL: selected rail %s failed re-init/configure\n", RAILS[best].name);
		return 0;
	}
	k_msleep((int32_t)(2U * period_us / 1000U) + 2);

	const float power_lsb_w = ina236_power_lsb_w(&mon);

	printk("ENERGY-CFG {\"rail\":\"%s\",\"addr\":%u,\"shunt_ohms\":%f,"
	       "\"current_lsb_a\":%f,\"power_lsb_w\":%f,\"adcrange\":%d,\"avg\":%u,"
	       "\"vbusct_us\":%u,\"vshct_us\":%u,\"sample_period_us\":%u,"
	       "\"cycles_per_s\":%u,\"samples_per_window\":%u,\"windows\":%u,"
	       "\"npu_dispatched\":%s,\"baseline\":\"cpu-spin-npu-idle\","
	       "\"rail_selected_by\":\"%s\",\"timestamp_source\":\"%s\"}\n",
	       RAILS[best].name,
	       (unsigned)RAILS[best].addr,
	       (double)RAILS[best].shunt_ohms,
	       (double)mon.current_lsb_a,
	       (double)power_lsb_w,
	       (int)range,
	       16U, /* SAMPLE_AVG = INA236_AVG_16 */
	       140U,
	       140U,
	       (unsigned)period_us,
	       (unsigned)cps,
	       (unsigned)SAMPLES_PER_WINDOW,
	       (unsigned)WINDOW_PAIRS,
	       npu_ready ? "true" : "false",
	       criterion,
	       g_dwt_in_use ? "dwt-cyccnt" : "k-cycle-get-32");

	/* --- The measurement ------------------------------------------------- */
	float    per_window_mj[WINDOW_PAIRS] = { 0.0f };
	uint32_t total_inferences            = 0;
	uint32_t n_last                      = 0;
	bool     all_ok                      = true;

	/* Expected window duration in ms, times the overrun allowance. */
	const uint32_t deadline_ms =
	    (uint32_t)(((uint64_t)SAMPLES_PER_WINDOW * period_us * WINDOW_DEADLINE_MULT) / 1000ULL);
	size_t pairs_used = 0;

	for (size_t w = 0; w < WINDOW_PAIRS; w++) {
		window_result act = {}, idl = {};

		/* Phase markers carry the kernel uptime so an EXTERNAL instrument's
		 * trace (a bench PSU log, a power analyser) can be aligned to the
		 * exact interval each phase occupied.  Printed before the window
		 * opens, so the console write is outside the integration interval. */
		printk("ENERGY-PHASE %u %s begin uptime_ms=%lld\n",
		       (unsigned)w,
		       phase_name(PHASE_ACTIVE),
		       (long long)k_uptime_get());
		run_window(&mon,
		           &interpreter,
		           PHASE_ACTIVE,
		           poll_cycles,
		           SAMPLES_PER_WINDOW,
		           deadline_ms,
		           power_lsb_w,
		           (float)cps,
		           &act);
		printk("ENERGY-PHASE %u %s end uptime_ms=%lld\n",
		       (unsigned)w,
		       phase_name(PHASE_ACTIVE),
		       (long long)k_uptime_get());
		float e_act = act.energy_mj;
		emit_window(w, PHASE_ACTIVE, act);

		printk("ENERGY-PHASE %u %s begin uptime_ms=%lld\n",
		       (unsigned)w,
		       phase_name(PHASE_IDLE),
		       (long long)k_uptime_get());
		run_window(&mon,
		           &interpreter,
		           PHASE_IDLE,
		           poll_cycles,
		           SAMPLES_PER_WINDOW,
		           deadline_ms,
		           power_lsb_w,
		           (float)cps,
		           &idl);
		printk("ENERGY-PHASE %u %s end uptime_ms=%lld\n",
		       (unsigned)w,
		       phase_name(PHASE_IDLE),
		       (long long)k_uptime_get());
		float e_idl = idl.energy_mj;
		emit_window(w, PHASE_IDLE, idl);

		/* A pair is only usable if inference ran AND both windows cover
		 * comparable wall-clock time.  windowed_delta() is a subtraction of
		 * two integrals, not a rate comparison, so mismatched durations bias
		 * the baseline -- a short idle window subtracts too little and
		 * inflates the per-inference figure.  10 % is well above the jitter
		 * a healthy pair shows (bench-observed: 1101 vs 1102 ms). */
		uint32_t span_lo     = act.span_ms < idl.span_ms ? act.span_ms : idl.span_ms;
		uint32_t span_hi     = act.span_ms > idl.span_ms ? act.span_ms : idl.span_ms;
		bool     spans_match = (span_hi == 0) ? false : ((span_hi - span_lo) * 10U <= span_hi);

		if (act.inferences == 0 || !spans_match || act.timed_out || idl.timed_out) {
			all_ok = false;
			printk("ENERGY-PAIR %u SKIPPED: n=%u spans %u/%u ms match=%d "
			       "timed_out=%d/%d\n",
			       (unsigned)w,
			       (unsigned)act.inferences,
			       (unsigned)act.span_ms,
			       (unsigned)idl.span_ms,
			       (int)spans_match,
			       (int)act.timed_out,
			       (int)idl.timed_out);
			continue;
		}
		per_window_mj[pairs_used++] = (e_act - e_idl) / (float)act.inferences;
		total_inferences += act.inferences;
		n_last = act.inferences;
		printk("ENERGY-PAIR %u active_mj=%f idle_mj=%f n=%u mj_per_inference=%f\n",
		       (unsigned)w,
		       (double)e_act,
		       (double)e_idl,
		       (unsigned)act.inferences,
		       (double)per_window_mj[pairs_used - 1]);
	}

	if (pairs_used == 0) {
		printk("RESULT FAIL: no usable (active, idle) pair -- see ENERGY-PAIR / "
		       "ENERGY-WERR lines above\n");
		return 0;
	}
	g_total_inferences = total_inferences;

	/* Mean and sample standard deviation across the pairs.  The spread is the
	 * honest error bar on the mean: a spread comparable to the value itself
	 * means the measurement is noise, and the reader must be able to see that
	 * rather than infer it. */
	float mean = 0.0f;
	for (size_t w = 0; w < pairs_used; w++) {
		mean += per_window_mj[w];
	}
	mean /= (float)pairs_used;

	/* Sample standard deviation needs at least two pairs; with one usable pair
	 * there is no spread to report, and reporting 0.0 would read as "perfectly
	 * repeatable" rather than "never repeated". */
	float spread      = 0.0f;
	bool  have_spread = (pairs_used >= 2);
	if (have_spread) {
		float var = 0.0f;
		for (size_t w = 0; w < pairs_used; w++) {
			float d = per_window_mj[w] - mean;
			var += d * d;
		}
		var /= (float)(pairs_used - 1);
		spread = (var > 0.0f) ? __builtin_sqrtf(var) : 0.0f;
	}
	g_mj_per_inference = mean;

	/* The device's own answer, in the host's schema.  `source` and `scope` are
	 * the labels the host contract validates -- carrier-rail delta, never
	 * silicon or NPU energy -- so they are emitted verbatim and never
	 * "upgraded" here. */
	printk("ENERGY-RESULT {\"source\":\"measured\",\"scope\":\"carrier-rail-delta\","
	       "\"value_mj_per_inference\":%f,\"rails\":[\"%s\"],\"n_inferences\":%u,"
	       "\"window_ms\":%f,\"sample_count\":%u,\"spread_mj\":%s%f,"
	       "\"pairs_used\":%u,\"total_inferences\":%u}\n",
	       (double)mean,
	       RAILS[best].name,
	       (unsigned)n_last,
	       (double)((float)SAMPLES_PER_WINDOW * (float)period_us / 1000.0f),
	       (unsigned)(SAMPLES_PER_WINDOW * 2U * pairs_used),
	       have_spread ? "" : "-", /* negative marks "no spread measured" */
	       (double)spread,
	       (unsigned)pairs_used,
	       (unsigned)total_inferences);

	if (mean > 0.0f) {
		printk("RESULT PASS: %f mJ/inference (+/-%f) rail=%s n=%u pairs=%u/%u "
		       "all_pairs_ok=%d\n",
		       (double)mean,
		       (double)spread,
		       RAILS[best].name,
		       (unsigned)n_last,
		       (unsigned)pairs_used,
		       (unsigned)WINDOW_PAIRS,
		       (int)all_ok);
	} else {
		/* A non-positive delta is a real outcome, not a crash: it means the
		 * inference load did not rise above this rail's noise.  Reporting it
		 * as FAIL keeps a meaningless number from being quoted as a result. */
		printk("RESULT FAIL: delta not resolvable -- mean=%f spread=%f all_windows_ok=%d "
		       "rail=%s (inference load below this rail's noise, or wrong rail)\n",
		       (double)mean,
		       (double)spread,
		       (int)all_ok,
		       RAILS[best].name);
	}

	ina236_deinit(&mon);
	return 0;
}
