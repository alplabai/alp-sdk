"""Regenerate src/models.h: two one-op (RELU, int8) .tflite flatbuffers.

    python3 tests/zephyr/inference_tflm_dim_bound/gen_models.py

Requires the `model-compile` extra (tflite + flatbuffers), like
tests/fixtures/models/gen_tiny_model.py, whose builders this reuses.
Output is passed through clang-format-22 by the caller; the file is
committed so the test needs no Python at build time."""
from __future__ import annotations

import sys
from pathlib import Path

import flatbuffers
import tflite as t

sys.path.insert(0, str(Path(__file__).resolve().parents[2] / "fixtures" / "models"))
import gen_tiny_model as g  # noqa: E402


def relu_model(dim: int) -> bytes:
    """input [1, dim] int8 -> RELU -> output [1, dim] int8."""
    b = flatbuffers.Builder(1024)
    buffers = g._offvec(b, t.ModelStartBuffersVector, [g._buffer(b, b"")])
    tin = g._tensor(b, [1, dim], t.TensorType.INT8, 0, "input", 0.0078125, -1)
    tout = g._tensor(b, [1, dim], t.TensorType.INT8, 0, "output", 0.0078125, -1)
    tensors = g._offvec(b, t.SubGraphStartTensorsVector, [tin, tout])
    sg_in = g._ivec(b, t.SubGraphStartInputsVector, [0])
    sg_out = g._ivec(b, t.SubGraphStartOutputsVector, [1])
    op_in = g._ivec(b, t.OperatorStartInputsVector, [0])
    op_out = g._ivec(b, t.OperatorStartOutputsVector, [1])
    t.OperatorStart(b)
    t.OperatorAddOpcodeIndex(b, 0)
    t.OperatorAddInputs(b, op_in)
    t.OperatorAddOutputs(b, op_out)
    op = t.OperatorEnd(b)
    operators = g._offvec(b, t.SubGraphStartOperatorsVector, [op])
    name = b.CreateString("main")
    t.SubGraphStart(b)
    t.SubGraphAddTensors(b, tensors)
    t.SubGraphAddInputs(b, sg_in)
    t.SubGraphAddOutputs(b, sg_out)
    t.SubGraphAddOperators(b, operators)
    t.SubGraphAddName(b, name)
    sg = t.SubGraphEnd(b)
    subgraphs = g._offvec(b, t.ModelStartSubgraphsVector, [sg])
    t.OperatorCodeStart(b)
    t.OperatorCodeAddDeprecatedBuiltinCode(b, t.BuiltinOperator.RELU)
    t.OperatorCodeAddBuiltinCode(b, t.BuiltinOperator.RELU)
    t.OperatorCodeAddVersion(b, 1)
    oc = t.OperatorCodeEnd(b)
    opcodes = g._offvec(b, t.ModelStartOperatorCodesVector, [oc])
    t.ModelStart(b)
    t.ModelAddVersion(b, 3)
    t.ModelAddOperatorCodes(b, opcodes)
    t.ModelAddSubgraphs(b, subgraphs)
    t.ModelAddBuffers(b, buffers)
    b.Finish(t.ModelEnd(b), b"TFL3")
    return bytes(b.Output())


def c_array(name: str, data: bytes) -> str:
    rows = ["\t" + ", ".join(f"0x{x:02x}" for x in data[i:i + 16]) + "," for i in range(0, len(data), 16)]
    return f"static const uint8_t __aligned(16) {name}[] = {{\n" + "\n".join(rows) + "\n};\n"


if __name__ == "__main__":
    out = Path(__file__).with_name("src") / "models.h"
    out.write_text(
        "/* SPDX-License-Identifier: Apache-2.0 */\n"
        "/* Generated by ../gen_models.py -- do not edit. */\n\n"
        "#include <stdint.h>\n#include <zephyr/toolchain.h>\n\n"
        "/* Largest dim the uint16_t shape[] can carry. */\n"
        + c_array("k_model_dim_65535", relu_model(65535))
        + "\n/* One past it: tflm_open() must refuse this. */\n"
        + c_array("k_model_dim_65536", relu_model(65536))
    )
    print(f"wrote {out}")
