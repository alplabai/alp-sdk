"""
Doc-drift gate -- fails (exit 1) when customer-facing documentation
references SDK identifiers that no longer exist, when a top-level
doc isn't linked from the docs index, or when CC3501E docs/examples
describe the current bridge as the obsolete CS-less design.

Five independent checks:

  (a) Dead-symbol references.  Every `ALP_[A-Z0-9_]+` and
      `alp_[a-z0-9_]+` token mentioned in a customer doc -- including a
      `CONFIG_`-prefixed one (`CONFIG_ALP_SDK_FOO=y`); the prefix is
      stripped before the known-symbol check, since Kconfig source
      spells the same symbol bare -- must exist as a token in one of
      the SDK's authoritative sources of truth:
        * C-API public + internal headers, sources
                                   include/**/*.h, src/**/*.h,
                                 src/**/*.c, src/**/*.cpp
        * Kconfig config symbols   zephyr/Kconfig[.alp-libraries],
                                 zephyr/kconfigs/*.kconfig
        * generated identifiers    scripts/alp_project.py + scripts/gen_*.py
          (the alp_hw_info_build CMake helper, ALP_HW_BUILD_* / ALP_SOC_*
           macros)
        * vendor integration anchors  vendors/**/CMakeLists.txt (e.g.
          ALP_HAS_RENESAS_FSP) -- a symbol a vendors/<lib>/README.md
          documents can be declared ONLY here, not under include/ or src/
        * real board targets       zephyr/boards/alp/<dir>/board.yml's
          `board: name:` field (e.g. alp_e1m_aen801_m55_he) -- EXISTENCE,
          not naming shape, is what makes a board name real; a token
          that merely looks like alp_e1m_<shape> but has no board.yml
          on disk is dead (see collect_real_board_names())
      A token that appears in the docs but in NONE of these is "dead" --
      almost always a rename the docs missed (e.g. the DEEPX_DX ->
      DEEPX_DXM1 / .alpmodel migration left ALP_..._DEEPX_DX behind).
      Harvesting from the real sources (rather than a hand-kept
      allowlist) keeps the gate low-maintenance and free of
      build-identifier false positives.

      Scanned surfaces (customer-facing only):
        README.md, docs/*.md (top-level), docs/tutorials/**,
        docs/soms/**, docs/boards/**, docs/bench/**, vendors/**/*.md
      Deliberately NOT scanned:
        * historical / generated / internal: CHANGELOG.md,
          docs/superpowers/**, docs/abi/**, docs/adr/**
        * forward-looking design/proposal docs that document not-yet-
          shipped APIs by intent (see _SCAN_EXCLUDE_DOCS)
      Not yet in scope (narrower than the sibling check_doc_links.py,
      which additionally covers docs/{diagnostics,ci}/** and
      examples/**/README.md): docs/ci/**, docs/diagnostics/**,
      docs/architecture/**, docs/metadata/**, examples/**/README.md.
      Widening this needs its own pass -- a spot-check of those
      directories turns up several ALP_*-shaped tokens that are CI/env
      var names, not SDK symbols (e.g. ALP_CI_APP_ID), so naively adding
      them would need new allowlist curation, not just a scan-surface
      flip.

  (b) Docs-index integrity.  Every top-level docs/*.md (except
      README.md itself) must be linked from docs/README.md.  This is
      the check the updating-docs skill documents in prose; here it is
      mechanised so CI enforces it.

  (c) CC3501E bridge-current wording.  Customer docs, the CC3501E firmware
      wrapper comments, and the AEN CC3501E examples must not describe the
      current bridge as the older CS-less / fixed-count design.  Explicitly
      historical "earlier r1" notes are allowed; current-rev guidance must say
      hardware SS0 + READY, with HOST_IRQ / async events as the remaining
      future work.

  (d) E1M-X pinout namespace guidance.  Standalone/general docs that teach
      developers to pick pinout instance IDs must present the E1M and E1M-X
      namespaces together (`<alp/e1m_pinout.h>` + `<alp/e1m_x_pinout.h>`).
      E1M-only guidance in those docs is drift because the form factors are
      intentionally separate product lines.

  (e) Portability-matrix totals.  docs/portability-matrix.md's generated
      block states the authoritative "N / M cells generate cleanly" count
      per family (regenerated by scripts/gen_portability_matrix.py,
      gated by pr-generated-files.yml).  Several narrative docs
      (docs/v1.0-readiness.md, docs/portability.md,
      docs/tutorials/04-cross-family-portability.md) hand-quote that
      count in prose ("18/21", "8 of 12", ...); nothing previously
      re-checked those quotes against the generated source, so they
      silently drifted when the SoM lineup changed (#1203).  Any
      hand-written "N/M" or "N of M" fraction whose denominator matches
      one of the matrix's own per-family totals must carry the matching
      numerator.

Run from the repo root:

    python3 scripts/check_doc_drift.py                  # both checks
    python3 scripts/check_doc_drift.py --allow ALP_FOO  # extend allowlist

Exits non-zero if any check finds a problem.
"""

