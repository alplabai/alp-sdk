def collect_known_symbols(root: pathlib.Path) -> set[str]:
    """Return every ALP_*/alp_* token that appears in ANY of the SDK's
    authoritative source layers.  An identifier is real (not drift) if it
    exists in any of these -- a doc reference present in NO source layer
    is what we flag.  Tests and docs are deliberately NOT sources of truth.

    Source layers harvested (each bounded to a specific directory -- never
    a whole-tree walk, so this stays fast and skips build artefacts):
      * C-API headers + sources  include/**/*.h, src/**/*.h,
                                 src/**/*.c, src/**/*.cpp
      * Kconfig config symbols   zephyr/Kconfig[.alp-libraries],
                                 zephyr/kconfigs/*.kconfig
      * CMake options / helpers  CMakeLists.txt, src/**/CMakeLists.txt,
                                 cmake/**/*.cmake, vendors/**/CMakeLists.txt
                                 (ALP_OS, ALP_SDK*, alp_hw_info_build,
                                 ALP_HAS_RENESAS_FSP, ...)
      * generators / tooling     scripts/**/*.py, excluding scripts/check_*.py
                                 gate scripts (board names,
                                 ALP_HW_BUILD_* / ALP_SOC_* macros,
                                 board.yaml field identifiers)
      * config schemas           metadata/schemas/*.json (board.yaml fields)
      * board-scoped app overlays  examples/**/boards/*.conf,
                                 examples/**/boards/*.overlay -- the full
                                 per-core board+SoC+core target identity
                                 (collect_real_board_names() only returns
                                 the bare board name)
      * release-signing keys      keys/*.pem
    """
    symbols: set[str] = set()

    def harvest(path: pathlib.Path) -> None:
        try:
            text = path.read_text(encoding="utf-8", errors="replace")
        except OSError:
            return
        symbols.update(m.group(1) for m in _BARE_SYMBOL_RE.finditer(text))

    def harvest_tree(base: pathlib.Path, pattern: str, *, exclude=None) -> None:
        if base.is_dir():
            for path in base.rglob(pattern):
                if exclude is not None and exclude(path):
                    continue
                harvest(path)

    def harvest_filenames(base: pathlib.Path, pattern: str) -> None:
        # Some real identifiers are proven by a filename's EXISTENCE on
        # disk, not by a declaration inside a source file -- same
        # principle as collect_real_board_names().  Match the symbol
        # shape against the filename text itself.
        if base.is_dir():
            for path in base.rglob(pattern):
                symbols.update(m.group(1) for m in _BARE_SYMBOL_RE.finditer(path.name))

    # C-API: public + internal headers, plus .c/.cpp sources -- some
    # symbols (e.g. the per-variant inference backend entry points) are
    # declared only in the .cpp that defines them, not a header.
    harvest_tree(root / "include", "*.h")
    harvest_tree(root / "src", "*.h")
    harvest_tree(root / "src", "*.c")
    harvest_tree(root / "src", "*.cpp")
    # Kconfig config namespace (ALP_SDK_*).  zephyr/Kconfig only sources the
    # per-subsystem fragments under zephyr/kconfigs/ (issue #458 split) plus a
    # couple of driver-tree Kconfig files, so harvest those directly too.
    for kconfig in ("zephyr/Kconfig", "zephyr/Kconfig.alp-libraries"):
        harvest(root / kconfig)
    harvest_tree(root / "zephyr" / "kconfigs", "*.kconfig")
    # CMake options / helper functions (ALP_OS, ALP_SDK*, alp_hw_info_build).
    # vendors/**/CMakeLists.txt is its own layer: a vendor integration
    # anchor (e.g. vendors/renesas-rzv2n/CMakeLists.txt's
    # option(ALP_HAS_RENESAS_FSP ...)) can be the ONLY place a symbol its
    # own vendors/<lib>/README.md documents is declared.
    harvest(root / "CMakeLists.txt")
    harvest_tree(root / "src", "CMakeLists.txt")
    harvest_tree(root / "cmake", "*.cmake")
    harvest_tree(root / "vendors", "CMakeLists.txt")
    # Generators / orchestrator / project tooling -- emit board target
    # names, ALP_HW_BUILD_* / ALP_SOC_* macros, board.yaml field identifiers.
    # Every scripts/check_*.py gate script (this file included) is
    # excluded from this harvest as a class, not just by name: a
    # gate script narrates ALP_*/alp_* tokens in comments, docstrings, and
    # allowlist rationale without ever declaring or generating one.  Left
    # in, any one of them can let a symbol it merely discusses
    # self-confirm as "known" and hide real drift forever; the actual
    # generators (alp_project.py, gen_*.py, alp_orchestrate/**) stay
    # harvested.
    harvest_tree(root / "scripts", "*.py",
                exclude=lambda p: p.name.startswith("check_"))
    # Config schemas -- board.yaml field names.
    harvest_tree(root / "metadata" / "schemas", "*.json")
    # Board-scoped app CONFIG/DT overlays: Zephyr's boards/<board_target>.conf
    # / boards/<board_target>.overlay convention, keyed by the full
    # board+SoC+core target identity (e.g. docs/aen-bench-bringup.md's
    # `boards/alp_e1m_aen801_m55_he_ae822fa0e5597ls0_rtss_he.conf`).  Bounded
    # to examples/ (where every customer-doc-referenced target identity
    # lives) rather than the whole tree, so this doesn't also walk
    # tests/**/boards/ fixtures or pick up build/west-managed dirs.
    harvest_filenames(root / "examples", "boards/*.conf")
    harvest_filenames(root / "examples", "boards/*.overlay")
    # Release-signing key filenames under keys/ (e.g.
    # keys/alp_release_signing_ecdsa_p256.pub.pem, documented by
    # docs/som-release-signing.md).
    harvest_filenames(root / "keys", "*.pem")
    # Yocto layer -- MACHINE / image variables (ALP_BOOT_DEVICE, ...).
    for pat in ("*.conf", "*.bb", "*.bbappend", "*.inc"):
        harvest_tree(root / "meta-alp-sdk", pat)
    return symbols


def collect_real_board_names(root: pathlib.Path) -> set[str]:
    """Return every real Zephyr board target name shipped in-tree, read
    from each zephyr/boards/alp/<dir>/board.yml's `board: name:` field.

    This is the ground-truth check the naming-shape regex it replaced
    was not: a board name that never landed (or was renamed before it
    did) matches the alp_e1m_[a-z0-9_]+ shape just as well as a real
    one -- only an actual board.yml on disk proves the board exists.
    """
    names: set[str] = set()
    boards_dir = root / "zephyr" / "boards" / "alp"
    if not boards_dir.is_dir():
        return names
    for board_yml in boards_dir.glob("*/board.yml"):
        try:
            text = board_yml.read_text(encoding="utf-8", errors="replace")
        except OSError:
            continue
        m = _BOARD_YML_NAME_RE.search(text)
        if m:
            names.add(m.group(1))
    return names


def doc_files_for_symbol_scan(root: pathlib.Path) -> list[pathlib.Path]:
    """Customer-facing docs scanned for dead symbols (spec scope)."""
    out: list[pathlib.Path] = []
    readme = root / "README.md"
    if readme.is_file():
        out.append(readme)
    docs = root / "docs"
    if docs.is_dir():
        out.extend(sorted(p for p in docs.glob("*.md")  # top-level only
                          if p.name not in _SCAN_EXCLUDE_DOCS))
        for sub in _DOC_SUBDIRS:
            d = docs / sub
            if d.is_dir():
                out.extend(sorted(d.rglob("*.md")))      # recursive
    vendors = root / "vendors"
    if vendors.is_dir():
        out.extend(sorted(vendors.rglob("*.md")))         # recursive
    return out


def _is_known(tok: str, known: set[str], allow: set[str]) -> bool:
    """A token is real if it is a known symbol (which includes real,
    in-tree board target names -- see collect_real_board_names()),
    allowlisted, or -- for trailing-underscore family/wildcard
    references like `ALP_E1M_*` (token captured as `ALP_E1M_`) -- a
    prefix of some real symbol."""
    if tok in known or tok in allow:
        return True
    if tok.endswith("_"):
        return any(s.startswith(tok) for s in known)
    return False


def find_dead_symbols(root: pathlib.Path, known: set[str],
                      allow: set[str]) -> list[tuple[str, int, str]]:
    """Return [(relpath, line_no, token)] for every dead symbol ref."""
    dead: list[tuple[str, int, str]] = []
    for doc in doc_files_for_symbol_scan(root):
        rel = doc.relative_to(root).as_posix()
        text = doc.read_text(encoding="utf-8", errors="replace")
        for line_no, line in enumerate(text.splitlines(), 1):
            for m in _SYMBOL_RE.finditer(line):
                tok = m.group(1)
                if not _is_known(tok, known, allow):
                    dead.append((rel, line_no, tok))
    return dead


def find_index_gaps(root: pathlib.Path) -> list[str]:
    """Return top-level docs/*.md filenames not linked from docs/README.md."""
    docs = root / "docs"
    index = docs / "README.md"
    if not index.is_file():
        return []
    # Include '.' in the filename class so dotted stems like
    # `v1.0-readiness.md` match (a bare [A-Za-z0-9_-]+ stops at the dot
    # and mis-extracts "0-readiness.md").
    linked = set(re.findall(r"[A-Za-z0-9_.-]+\.md",
                            index.read_text(encoding="utf-8")))
    gaps: list[str] = []
    for md in sorted(docs.glob("*.md")):
        if md.name == "README.md":
            continue
        # Leading-underscore files are section fragments folded into another
        # doc (e.g. _aen-runbook-section.md -> bring-up-aen.md), not standalone
        # index entries.
        if md.name.startswith("_"):
            continue
        if md.name not in linked:
            gaps.append(md.name)
    return gaps


def cc3501e_bridge_current_files(root: pathlib.Path) -> list[pathlib.Path]:
    """Files whose CC3501E bridge-current wording should stay in sync."""
    seen: set[pathlib.Path] = set()
    out: list[pathlib.Path] = []
    for pattern in _CC3501E_BRIDGE_SCAN_GLOBS:
        for path in root.glob(pattern):
            if not path.is_file():
                continue
            if path.suffix not in _CC3501E_BRIDGE_SCAN_SUFFIXES:
                continue
            if path in seen:
                continue
            seen.add(path)
            out.append(path)
    return sorted(out)


def find_cc3501e_bridge_stale_claims(root: pathlib.Path) -> list[tuple[str, int, str]]:
    """Return stale current-rev CC3501E bridge wording references."""
    stale: list[tuple[str, int, str]] = []
    for path in cc3501e_bridge_current_files(root):
        rel = path.relative_to(root).as_posix()
        text = path.read_text(encoding="utf-8", errors="replace")
        for line_no, line in enumerate(text.splitlines(), 1):
            if not _CC3501E_STALE_BRIDGE_RE.search(line):
                continue
            if _CC3501E_STALE_ALLOWED_RE.search(line):
                continue
            stale.append((rel, line_no, line.strip()))
    return stale


def find_e1m_x_pinout_guidance_gaps(root: pathlib.Path) -> list[tuple[str, int, str]]:
    """Return E1M-only pinout guidance in standalone/general docs."""
    gaps: list[tuple[str, int, str]] = []
    for rel in _PINOUT_GUIDANCE_DOCS:
        path = root / rel
        if not path.is_file():
            continue
        text = path.read_text(encoding="utf-8", errors="replace")
        line_no = 1
        for para in re.split(r"\n\s*\n", text):
            if (
                _E1M_PINOUT_GUIDANCE_RE.search(para)
                and _PINOUT_TEACHING_RE.search(para)
                and not _E1M_X_PINOUT_GUIDANCE_RE.search(para)
            ):
                first = next((ln.strip() for ln in para.splitlines() if ln.strip()), "")
                gaps.append((rel, line_no, first))
            line_no += para.count("\n") + 2
    return gaps


def find_matrix_total_drift(root: pathlib.Path) -> list[tuple[str, int, str, str]]:
    """Return stale hand-quoted portability-matrix totals.

    Reads the authoritative "N / M cells generate cleanly" line(s) from
    the GENERATED block of docs/portability-matrix.md, then scans
    _MATRIX_TOTAL_QUOTING_DOCS for any "N/M" or "N of M" fraction whose
    denominator matches one of those totals.  Only the denominator is
    used to key the match -- 21 and 12 are specific to the current
    (SKU x example) cell counts, so an unrelated fraction elsewhere in
    the same docs (a tutorial count, a per-driver progress fraction)
    won't collide.
    """
    matrix_doc = root / "docs" / "portability-matrix.md"
    if not matrix_doc.is_file():
        return []
    matrix_text = matrix_doc.read_text(encoding="utf-8", errors="replace")
    authoritative = {
        int(total): int(passed)
        for passed, total in _MATRIX_TOTAL_RE.findall(matrix_text)
    }
    if not authoritative:
        return []

    drift: list[tuple[str, int, str, str]] = []
    for rel in _MATRIX_TOTAL_QUOTING_DOCS:
        path = root / rel
        if not path.is_file():
            continue
        text = path.read_text(encoding="utf-8", errors="replace")
        for pattern in (_STATED_SLASH_FRACTION_RE, _STATED_OF_FRACTION_RE):
            for m in pattern.finditer(text):
                stated_pass, stated_total = int(m.group(1)), int(m.group(2))
                if stated_total not in authoritative:
                    continue
                expected_pass = authoritative[stated_total]
                if stated_pass != expected_pass:
                    line_no = text.count("\n", 0, m.start()) + 1
                    drift.append((rel, line_no, m.group(0).replace("\n", " "),
                                  f"{expected_pass}/{stated_total}"))
    return drift


def find_example_preset_count_drift(root: pathlib.Path) -> list[tuple[str, int, str, str]]:
    """Return a stale hand-quoted example/preset-adoption count.

    docs/board-config-schema.md hand-quotes how many `examples/**/board.yaml`
    files exist and how many use each preset ("100 do today -- 75 on
    `e1m-evk`, 25 on `e1m-x-evk`"). Recompute the real counts by walking the
    tree and comparing `preset:` values, instead of trusting the prose to
    stay in sync -- the same drift this line has already suffered twice
    (66/46/20, then 100/75/25).
    """
    doc_path = root / "docs" / "board-config-schema.md"
    examples_dir = root / "examples"
    if not doc_path.is_file() or not examples_dir.is_dir():
        return []

    board_yamls = sorted(examples_dir.glob("**/board.yaml"))
    evk = x_evk = 0
    for p in board_yamls:
        m = re.search(r"(?m)^preset:\s*(\S+)",
                       p.read_text(encoding="utf-8", errors="replace"))
        if not m:
            continue
        if m.group(1) == "e1m-evk":
            evk += 1
        elif m.group(1) == "e1m-x-evk":
            x_evk += 1
    actual = (len(board_yamls), evk, x_evk)

    text = doc_path.read_text(encoding="utf-8", errors="replace")
    drift: list[tuple[str, int, str, str]] = []
    for m in _EXAMPLE_PRESET_COUNT_RE.finditer(text):
        stated = (int(m.group(1)), int(m.group(2)), int(m.group(3)))
        if stated != actual:
            line_no = text.count("\n", 0, m.start()) + 1
            drift.append((
                "docs/board-config-schema.md", line_no, m.group(0),
                f"({actual[0]} do today — {actual[1]} on `e1m-evk`, "
                f"{actual[2]} on `e1m-x-evk`)",
            ))
    return drift


def main(argv: Optional[list[str]] = None) -> int:
    parser = argparse.ArgumentParser(
        description=__doc__,
        formatter_class=argparse.RawDescriptionHelpFormatter,
    )
    parser.add_argument("--root", default=str(ROOT),
                        help="repo root to scan (default: the alp-sdk checkout)")
    parser.add_argument("--allow", action="append", default=[], metavar="SYMBOL",
                        help="extend the dead-symbol allowlist (repeatable)")
    args = parser.parse_args(argv)

    root = pathlib.Path(args.root).resolve()
    allow = _ALLOWLIST | set(args.allow)

    known = collect_known_symbols(root) | collect_real_board_names(root)
    dead = find_dead_symbols(root, known, allow)
    gaps = find_index_gaps(root)
    stale_cc3501e = find_cc3501e_bridge_stale_claims(root)
    e1m_x_pinout_gaps = find_e1m_x_pinout_guidance_gaps(root)
    matrix_total_drift = find_matrix_total_drift(root)
    example_preset_count_drift = find_example_preset_count_drift(root)

    if dead:
        print("Dead SDK-symbol references "
              "(token not found in headers / Kconfig / generators):",
              file=sys.stderr)
        for rel, line_no, tok in dead:
            print(f"  {rel}:{line_no}  {tok}", file=sys.stderr)
    if gaps:
        print("Top-level docs/*.md not linked from docs/README.md:",
              file=sys.stderr)
        for name in gaps:
            print(f"  docs/{name}", file=sys.stderr)
    if stale_cc3501e:
        print("Stale CC3501E bridge-current wording "
              "(current rev is hardware SS0 + READY; HOST_IRQ is future):",
              file=sys.stderr)
        for rel, line_no, line in stale_cc3501e:
            print(f"  {rel}:{line_no}  {line}", file=sys.stderr)
    if e1m_x_pinout_gaps:
        print("E1M-only pinout guidance in standalone/general docs "
              "(also mention <alp/e1m_x_pinout.h> / ALP_E1M_X_*):",
              file=sys.stderr)
        for rel, line_no, line in e1m_x_pinout_gaps:
            print(f"  {rel}:{line_no}  {line}", file=sys.stderr)
    if matrix_total_drift:
        print("Portability-matrix totals quoted in narrative docs don't "
              "match the generated docs/portability-matrix.md (regenerate "
              "via scripts/gen_portability_matrix.py, then fix the prose):",
              file=sys.stderr)
        for rel, line_no, matched, expected in matrix_total_drift:
            print(f"  {rel}:{line_no}  \"{matched}\" -- matrix says {expected}",
                  file=sys.stderr)
    if example_preset_count_drift:
        print("Example/preset-adoption count quoted in prose doesn't match "
              "examples/**/board.yaml's preset: fields:", file=sys.stderr)
        for rel, line_no, matched, expected in example_preset_count_drift:
            print(f"  {rel}:{line_no}  \"{matched}\" -- tree says {expected}",
                  file=sys.stderr)

    if (dead or gaps or stale_cc3501e or e1m_x_pinout_gaps
            or matrix_total_drift or example_preset_count_drift):
        print(f"\ndoc-drift: {len(dead)} dead ref(s), {len(gaps)} index "
              f"gap(s), {len(stale_cc3501e)} stale CC3501E bridge "
              f"claim(s), {len(e1m_x_pinout_gaps)} E1M-X pinout "
              f"guidance gap(s), {len(matrix_total_drift)} stale matrix "
              f"total(s), {len(example_preset_count_drift)} stale example "
              f"preset count(s) -- failing.", file=sys.stderr)
        return 1

    print("doc-drift: OK (no dead symbol refs, docs index complete, "
          "CC3501E bridge wording current, E1M-X pinout guidance current, "
          "portability-matrix totals in sync, example preset count in "
          "sync).")
    return 0


if __name__ == "__main__":
    sys.exit(main())
