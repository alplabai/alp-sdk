"""
Generate the Linux camera devicetree fragments and the kernel config fragment
from metadata, so adding a camera is a metadata-only change (#2633).

Outputs, all committed and all marked DO NOT EDIT BY HAND:

  meta-alp-sdk/recipes-kernel/linux/linux-renesas/
      e1m-x-evk-<connector>-<module_id>.dtsi   one per (camera module x
                                               carrier camera connector) the
                                               SoMs can host
      camera-sensors.cfg                       union of every module's
                                               drivers.linux.kconfig and the
                                               SoC receiver/capture symbols
  docs/v2n-camera-csi.md                       the supported-camera table
                                               between its GENERATED markers

Inputs (nothing is restated here; every value is read):

  metadata/camera_modules/<id>.yaml   module: chip, i2c address, xclk, lanes
  metadata/chips/<chip>.yaml          drivers.linux (compatible, kconfig,
                                      link_freqs, clock_name, reset_property,
                                      endpoint_flags), i2c.max_clock_hz,
                                      families
  metadata/boards/<board>.yaml        camera_connectors + e1m_routes
  metadata/e1m_modules/E1M-*.yaml     pad_routes (E1M pad -> SoC peripheral /
                                      GD32 bridge / unrouted)
  metadata/socs/**.json               linux_dt (DT labels, pinmux, kconfig)
  metadata/e1m_modules/<fam>/*.tsv    pad of each peripheral signal, GD32
                                      GPIO line order

A (module, connector) pair is generated for every SoM whose chip `families`
match and whose SoC declares `linux_dt`; all such SoMs must resolve to the
same fragment.  A route that is TBD or missing is NEVER guessed: the fragment
carries a `GAP` comment and the run fails naming the missing metadata.

Usage:

    python3 scripts/gen_camera_dt.py            # (re)write the outputs
    python3 scripts/gen_camera_dt.py --check    # exit 1 on drift or a gap
"""

from __future__ import annotations

import argparse
import json
import re
import sys
from pathlib import Path
from typing import Any

try:
    import yaml  # type: ignore[import-untyped]
except ImportError:
    sys.exit("gen_camera_dt: PyYAML required.  pip install pyyaml")

REPO = Path(__file__).resolve().parent.parent
sys.path.insert(0, str(REPO / "scripts"))
from alp_project_loader import _sku_family  # noqa: E402

LINUX_DIR = Path("meta-alp-sdk/recipes-kernel/linux/linux-renesas")
CFG_NAME = "camera-sensors.cfg"
DOC = Path("docs/v2n-camera-csi.md")
BANNER = "GENERATED by scripts/gen_camera_dt.py"
TABLE_BEGIN = "<!-- BEGIN GENERATED: scripts/gen_camera_dt.py supported cameras -->"
TABLE_END = "<!-- END GENERATED: scripts/gen_camera_dt.py supported cameras -->"

# SoM dispatch kind -> (DT label of its GPIO controller, dtsi that defines it).
# The line index is derived from the row order of gd32-io-mcu-map.tsv and
# cross-checked against that dtsi's gpio-line-names.
_GPIO_DISPATCH = {"gd32_bridge": ("gd32_gpio", "e1m-v2n-som.dtsi")}
# Every Renesas SoC dtsi labels its pin controller `pinctrl`.
_PINCTRL = "pinctrl"


def _yaml(path: Path) -> Any:
    return yaml.safe_load(path.read_text(encoding="utf-8"))


def _tsv_rows(path: Path) -> list[list[str]]:
    lines = path.read_text(encoding="utf-8").splitlines()[1:]
    return [ln.split("\t") for ln in lines if ln.strip()]


def _hex(v: int) -> str:
    return f"0x{v:x}"


def _line_name(macro: str) -> str:
    """XEVK_PIN_CAM0_MUX_SEL -> cam0-mux-sel"""
    return macro.split("_PIN_", 1)[-1].lower().replace("_", "-")


class Tree:
    """Everything read from <root>/metadata for one generator run."""

    def __init__(self, root: Path):
        self.root = root
        meta = root / "metadata"
        self.modules = {p.stem: _yaml(p)
                        for p in sorted((meta / "camera_modules").glob("*.yaml"))}
        self.boards = {}
        for p in sorted((meta / "boards").glob("*.yaml")):
            doc = _yaml(p)
            if isinstance(doc, dict) and doc.get("camera_connectors"):
                self.boards[p.stem] = doc
        self.soms = {}
        for p in sorted((meta / "e1m_modules").glob("E1M-*.yaml")):
            doc = _yaml(p)
            self.soms[doc["sku"]] = doc
        self._chips: dict[str, Any] = {}
        self._socs: dict[str, Any] = {}

    def chip(self, chip_id: str) -> dict | None:
        if chip_id not in self._chips:
            p = self.root / "metadata" / "chips" / f"{chip_id}.yaml"
            self._chips[chip_id] = _yaml(p) if p.is_file() else None
        return self._chips[chip_id]

    def soc(self, ref: str) -> dict:
        if ref not in self._socs:
            p = self.root / "metadata" / "socs" / (ref.replace(":", "/") + ".json")
            self._socs[ref] = json.loads(p.read_text(encoding="utf-8")) if p.is_file() else {}
        return self._socs[ref]

    def som_map(self, som: dict, name: str) -> Path | None:
        # V2M reuses the V2N pinout in full, so its map files live under v2n/.
        fam = _sku_family(som["sku"])
        for d in (fam, "v2n"):
            p = self.root / "metadata" / "e1m_modules" / d / name
            if p.is_file():
                return p
        return None

    def hosts(self, chip: dict) -> list[dict]:
        """SoMs that run Linux (their SoC has linux_dt) and carry this chip."""
        fams = set(chip.get("families") or [])
        return [s for s in self.soms.values()
                if _sku_family(s["sku"]) in fams and self.soc(s["silicon"]).get("linux_dt")]


# ---------------------------------------------------------------- resolution

def _route(som: dict, e1m: str) -> dict | None:
    return next((r for r in som.get("pad_routes") or [] if r.get("e1m") == e1m), None)


def _resolve_gpio(tree: Tree, board: dict, som: dict, macro: str, what: str) -> tuple:
    """Return ('gpio', label, line, active_low) | ('unrouted',) | ('gap', msg)."""
    entry = next((g for g in (board.get("e1m_routes") or {}).get("gpio") or []
                  if g.get("macro") == macro), None)
    if entry is None:
        return ("gap", f"board e1m_routes.gpio has no macro {macro} (needed by {what})")
    e1m = entry["e1m"]
    route = _route(som, e1m)
    if route is None:
        return ("gap", f"SoM pad_routes has no {e1m} entry (needed by {what})")
    kind = route.get("dispatch")
    if kind == "unrouted":
        return ("unrouted",)
    if kind not in _GPIO_DISPATCH:
        return ("gap", f"SoM pad_routes {e1m} dispatch is {kind}: no Linux GPIO "
                       f"controller is described for it (needed by {what})")
    label, dtsi = _GPIO_DISPATCH[kind]
    tsv = tree.som_map(som, "gd32-io-mcu-map.tsv")
    n = re.fullmatch(r"E1M_X_GPIO_IO(\d+)", e1m)
    rows = [r[0] for r in _tsv_rows(tsv) if re.fullmatch(r"E1M IO\d+", r[0])] if tsv else []
    if not n or f"E1M IO{n.group(1)}" not in rows:
        return ("gap", f"gd32-io-mcu-map.tsv has no `E1M IO{n.group(1) if n else '?'}` row "
                       f"(needed by {what})")
    line = rows.index(f"E1M IO{n.group(1)}")
    bad = _check_line_names(tree, dtsi, label, f"IO{n.group(1)}", line)
    if bad:
        return ("gap", bad)
    return ("gpio", label, line, bool(entry.get("active_low")))


def _check_line_names(tree: Tree, dtsi: str, label: str, name: str, line: int) -> str | None:
    p = tree.root / LINUX_DIR / dtsi
    if not p.is_file():
        return f"{LINUX_DIR / dtsi} is missing: cannot confirm GPIO line {line} of {label}"
    text = p.read_text(encoding="utf-8")
    m = re.search(rf"{label}:.*?gpio-line-names\s*=(.*?);", text, re.S)
    names = re.findall(r'"([^"]*)"', re.sub(r"/\*.*?\*/", "", m.group(1), flags=re.S)) if m else []
    if name not in names or names.index(name) != line:
        got = names.index(name) if name in names else "absent"
        return (f"gd32-io-mcu-map.tsv row order puts {name} on {label} line {line} but "
                f"{dtsi} gpio-line-names has it at {got}")
    return None


def _resolve_bus(tree: Tree, board: dict, som: dict, macro: str, what: str) -> tuple:
    """('i2c', label, [(pad, function, fn_code)], macro_name) | ('gap', msg)."""
    entry = next((b for b in (board.get("e1m_routes") or {}).get("buses") or []
                  if b.get("macro") == macro), None)
    if entry is None:
        return ("gap", f"board e1m_routes.buses has no macro {macro} (needed by {what})")
    inst = _soc_instance(tree, som, entry["e1m"], what)
    if inst[0] == "gap":
        return inst
    pin, ent = inst[1], inst[2]
    pm = ent.get("pinmux") or {}
    if pm and not ent.get("pinmux_macro"):
        return ("gap", f"SoC linux_dt.{pin}.pinmux_macro is missing (needed by {what})")
    tsv = tree.som_map(som, "renesas-peripheral-map.tsv")
    sigs = {r[0]: r for r in _tsv_rows(tsv)} if tsv else {}
    cells = []
    for sig, fn in pm.items():
        row = sigs.get(sig)
        if row is None or len(row) < 4:
            return ("gap", f"renesas-peripheral-map.tsv has no pad row for signal {sig} "
                           f"(linux_dt.{pin}.pinmux, needed by {what})")
        mm = re.fullmatch(r"P(\d+)(\d)", row[1])
        if not mm:
            return ("gap", f"signal {sig} pad {row[1]} is not a P<port><pin> pad")
        cells.append((int(mm.group(1)), int(mm.group(2)), fn, row[3]))
    return ("i2c", ent["label"], cells, ent.get("pinmux_macro"), pin)


def _soc_instance(tree: Tree, som: dict, e1m: str, what: str) -> tuple:
    route = _route(som, e1m)
    if route is None:
        return ("gap", f"SoM pad_routes has no {e1m} entry (needed by {what})")
    if route.get("dispatch") != "direct":
        return ("gap", f"SoM pad_routes {e1m} dispatch is {route.get('dispatch')}, "
                       f"not direct (needed by {what})")
    pin = route.get("dispatch_pin")
    ent = (tree.soc(som["silicon"]).get("linux_dt") or {}).get(pin)
    if ent is None:
        return ("gap", f"SoC {som['silicon']} linux_dt has no {pin} entry (needed by {what})")
    return ("ok", pin, ent)


def _resolve(tree: Tree, board: dict, conn: dict, som: dict, name: str) -> dict:
    """Everything the fragment needs from the SoM + SoC side, for one SoM."""
    csi = _soc_instance(tree, som, conn["csi"], f"camera_connectors.{name}.csi")
    gpios = {}
    for sel in conn.get("select") or []:
        gpios["select:" + sel["gpio"]] = (
            _resolve_gpio(tree, board, som, sel["gpio"], f"camera_connectors.{name}.select"), sel["value"])
    for key in ("enable", "reset"):
        if conn.get(key):
            gpios[key] = (_resolve_gpio(tree, board, som, conn[key],
                                        f"camera_connectors.{name}.{key}"), None)
    return {"csi": ("csi", csi[2]["label"], csi[2].get("capture")) if csi[0] == "ok" else csi,
            "i2c": _resolve_bus(tree, board, som, conn["i2c"], f"camera_connectors.{name}.i2c"),
            "gpios": gpios}


def _gaps(res: dict) -> list[str]:
    out = []
    for v in (res["csi"], res["i2c"]):
        if v[0] == "gap":
            out.append(v[1])
    out += [g[0][1] for g in res["gpios"].values() if g[0][0] == "gap"]
    return out


# ------------------------------------------------------------------ render

def _render(board_name: str, conn_name: str, conn: dict, mod: dict, chip: dict,
            res: dict, extra_gaps: list[str]) -> str:
    drv = chip["drivers"]["linux"]
    c = conn_name.lower()
    idx = int(re.sub(r"\D", "", conn_name) or 0)
    lanes = mod["lanes"]
    dl = " ".join(str(i + 1) for i in range(lanes))
    gaps = _gaps(res) + extra_gaps
    csi_label, cap = res["csi"][1:3] if res["csi"][0] == "csi" else ("?", None)

    hdr = ["// SPDX-License-Identifier: (GPL-2.0-only OR BSD-2-Clause)", "/*",
           f" * {BANNER} -- DO NOT EDIT BY HAND.",
           f" * {mod['display_name']} on {board_name} {conn_name} ({conn['refdes']}):",
           f" * {conn['csi']} -> &{csi_label} -> &{cap} -> /dev/video*.",
           " * Inputs: metadata/camera_modules/" + mod["module_id"] + ".yaml, metadata/chips/"
           + mod["chip"] + ".yaml,",
           f" * metadata/boards/{board_name}.yaml camera_connectors.{conn_name}, SoM pad_routes, "
           "SoC linux_dt.",
           " * Regenerate: python3 scripts/gen_camera_dt.py"]
    for g in gaps:
        hdr.append(f" * GAP (metadata missing, run gen_camera_dt.py --check): {g}")
    hdr.append(" */")
    L = hdr + [""]

    L += ["/ {", "\taliases {", f"\t\talp-camera{idx} = &{c}_sensor;", "\t};", "",
          f"\t{c}_xclk: {c}-xclk {{", '\t\tcompatible = "fixed-clock";', "\t\t#clock-cells = <0>;",
          f"\t\tclock-frequency = <{mod['xclk_hz']}>;", "\t};", "};", ""]

    # Connector GPIOs: select + enable are hogs, reset is a sensor property.
    hogs: dict[str, list[str]] = {}
    reset_prop = None
    notes = []
    for key, (g, value) in res["gpios"].items():
        macro = key.split(":", 1)[1] if key.startswith("select:") else conn[key]
        if g[0] == "unrouted":
            notes.append(f"{macro}: not routed to a Linux GPIO controller, not modelled")
        elif g[0] == "gpio":
            _, label, line, active_low = g
            if key.startswith("select:"):
                flags, level = "GPIO_ACTIVE_HIGH", "output-high" if value else "output-low"
                why = f"{macro} = line {line}: raw level {'HIGH' if value else 'LOW'} routes {conn['refdes']}."
            elif key == "enable":
                flags = "GPIO_ACTIVE_LOW" if active_low else "GPIO_ACTIVE_HIGH"
                level, why = "output-high", f"{macro} = line {line}: asserted = camera on."
            else:
                flags = "GPIO_ACTIVE_LOW" if active_low else "GPIO_ACTIVE_HIGH"
                if drv.get("reset_property"):
                    reset_prop = f"{drv['reset_property']} = <&{label} {line} {flags}>;"
                continue
            hogs.setdefault(label, []).extend([
                "\t/* " + why + " */", f"\t{_line_name(macro)}-hog {{", "\t\tgpio-hog;",
                f"\t\tgpios = <{line} {flags}>;", f"\t\t{level};",
                f'\t\tline-name = "{_line_name(macro)}";', "\t};"])
    for label, body in hogs.items():
        L += [f"&{label} {{"] + body + ["};", ""]
    for n in notes:
        L.append(f"/* {n}. */")
    if notes:
        L.append("")

    if res["i2c"][0] == "i2c":
        _, i2c_label, cells, pm_macro, pin = res["i2c"]
        L += [f"&{_PINCTRL} {{", f"\t/* {conn['i2c']} = {pin} */", f"\t{i2c_label}_pins: {i2c_label} {{"]
        for i, (port, pn, fn, func) in enumerate(cells):
            first = "\t\tpinmux = " if i == 0 else "\t\t\t "
            end = ";" if i == len(cells) - 1 else ","
            L.append(f"{first}<{pm_macro}({port}, {pn}, {fn})>{end} /* {func} */")
        L += ["\t};", "};", ""]
        L += [f"&{i2c_label} {{", f"\tpinctrl-0 = <&{i2c_label}_pins>;", '\tpinctrl-names = "default";']
        hz = (chip.get("i2c") or {}).get("max_clock_hz")
        if hz:
            L.append(f"\tclock-frequency = <{hz}>;")
        L += ['\tstatus = "okay";', ""]
        ep = [f"\t\t\t\tremote-endpoint = <&{c}_csi_in>;", f"\t\t\t\tdata-lanes = <{dl}>;"]
        freqs = next((e["link_freqs_hz"] for e in drv.get("link_freqs") or []
                      if e["lanes"] == lanes), None)
        if freqs:
            ep.append("\t\t\t\tlink-frequencies = /bits/ 64 <"
                      + "> <".join(str(f) for f in freqs) + ">;")
        ep += [f"\t\t\t\t{f};" for f in drv.get("endpoint_flags") or []]
        sensor = [f"\t{c}_sensor: camera@{mod['i2c_addr_7bit']:x} {{",
                  f'\t\tcompatible = "{drv["compatible"]}";',
                  f"\t\treg = <{_hex(mod['i2c_addr_7bit'])}>;", f"\t\tclocks = <&{c}_xclk>;"]
        if drv.get("clock_name"):
            sensor.append(f'\t\tclock-names = "{drv["clock_name"]}";')
        if reset_prop:
            sensor.append("\t\t" + reset_prop)
        sensor += ["", "\t\tport {", f"\t\t\t{c}_sensor_out: endpoint {{"] + ep + ["\t\t\t};", "\t\t};", "\t};"]
        L += sensor + ["};", ""]

    if res["csi"][0] == "csi":
        pol = conn.get("lane_polarity")
        L += [f"&{csi_label} {{", '\tstatus = "okay";', "", "\tports {",
              "\t\t#address-cells = <1>;", "\t\t#size-cells = <0>;", "",
              "\t\tport@0 {", "\t\t\treg = <0>;", f"\t\t\t{c}_csi_in: endpoint {{",
              f"\t\t\t\tremote-endpoint = <&{c}_sensor_out>;", f"\t\t\t\tdata-lanes = <{dl}>;"]
        if pol:
            L.append(f"\t\t\t\t/* camera_connectors.{conn_name}.lane_polarity (clock first). */")
            L.append("\t\t\t\tlane-polarities = <" + " ".join(str(p) for p in pol[:lanes + 1]) + ">;")
        L += ["\t\t\t};", "\t\t};", "\t};", "};", "", f"&{cap} {{", '\tstatus = "okay";', "};", ""]
    return "\n".join(L).rstrip("\n") + "\n"


# ---------------------------------------------------------------- generation

def _pairs(tree: Tree) -> tuple[list[dict], list[str]]:
    """One record per generated fragment, plus every problem found."""
    pairs, problems = [], []
    for mid, mod in tree.modules.items():
        chip = tree.chip(mod["chip"])
        if chip is None:
            problems.append(f"camera module {mid}: chip {mod['chip']} has no metadata/chips/{mod['chip']}.yaml")
            continue
        hosts = tree.hosts(chip)
        if not hosts:
            continue  # no Linux SoM carries this chip: nothing to generate
        lin = (chip.get("drivers") or {}).get("linux") or {}
        if not lin.get("compatible"):
            problems.append(f"chip {mod['chip']}: drivers.linux.compatible is missing "
                            f"(module {mid} is hosted by {', '.join(sorted(s['sku'] for s in hosts))})")
            continue
        for bname, board in tree.boards.items():
            for cname, conn in board["camera_connectors"].items():
                if mod["lanes"] > conn["lanes"]:
                    continue  # module cannot plug into this connector
                by_res: dict[str, list[str]] = {}
                resolved: dict[str, dict] = {}
                for som in hosts:
                    r = _resolve(tree, board, conn, som, cname)
                    k = json.dumps(r, sort_keys=True, default=list)
                    by_res.setdefault(k, []).append(som["sku"])
                    resolved[k] = r
                extra = []
                if len(by_res) > 1:
                    extra.append("SoMs resolve to different routes: " + "; ".join(
                        ", ".join(v) for v in by_res.values()))
                    problems.append(f"{mid} on {bname} {cname}: " + extra[0])
                k0 = next(iter(by_res))
                res = resolved[k0]
                for g in _gaps(res):
                    problems.append(f"{mid} on {bname} {cname} ({', '.join(by_res[k0])}): metadata gap: {g}")
                name = f"{bname}-{cname.lower()}-{mid}.dtsi"
                pairs.append({"file": LINUX_DIR / name, "module": mid, "connector": cname,
                              "board": bname, "text": _render(bname, cname, conn, mod, chip, res, extra),
                              "chip": chip, "mod": mod, "conn": conn})
    return pairs, problems


def _cfg(tree: Tree) -> str:
    syms: set[str] = set()
    for mod in tree.modules.values():
        k = (((tree.chip(mod["chip"]) or {}).get("drivers") or {}).get("linux") or {}).get("kconfig")
        if k:
            syms.add(k)
    for som in tree.soms.values():
        for ent in (tree.soc(som["silicon"]).get("linux_dt") or {}).values():
            syms.update(ent.get("kconfig") or [])
    return ("# " + BANNER + " -- DO NOT EDIT BY HAND.\n"
            "# Camera capture stack + every supported sensor driver, built in (=y) on every\n"
            "# V2N/V2M machine (alp-image-* installs no kernel-modules package).  Union of the\n"
            "# SoC receiver/capture symbols (metadata/socs linux_dt.*.kconfig) and every\n"
            "# camera module chip's drivers.linux.kconfig.\n"
            "# Regenerate: python3 scripts/gen_camera_dt.py\n"
            + "".join(f"{s}=y\n" for s in sorted(syms)))


def _table(tree: Tree, pairs: list[dict]) -> str:
    rows = [TABLE_BEGIN, "",
            "| Module | Sensor | Connector | Lanes | I2C | Linux driver | `ALP_CAMERA_<connector>` |",
            "|---|---|---|---|---|---|---|"]
    for p in sorted(pairs, key=lambda p: (p["connector"], p["module"])):
        m, ch = p["mod"], p["chip"]
        rows.append(f"| {m['display_name']} | `{m['chip']}` | {p['connector']} ({p['conn']['refdes']}) | "
                    f"{m['lanes']} | `{_hex(m['i2c_addr_7bit'])}` | "
                    f"`{ch['drivers']['linux']['compatible']}` | `{m['module_id']}` |")
    rows += ["", TABLE_END]
    return "\n".join(rows)


def generate(root: Path) -> tuple[dict[Path, str], list[str]]:
    """(relative path -> content, problems).  Pure: reads root, writes nothing."""
    tree = Tree(root)
    pairs, problems = _pairs(tree)
    out = {p["file"]: p["text"] for p in pairs}
    out[LINUX_DIR / CFG_NAME] = _cfg(tree)
    doc = root / DOC
    if doc.is_file():
        text = doc.read_text(encoding="utf-8")
        if TABLE_BEGIN in text and TABLE_END in text:
            a, b = text.index(TABLE_BEGIN), text.index(TABLE_END) + len(TABLE_END)
            out[DOC] = text[:a] + _table(tree, pairs) + text[b:]
        else:
            problems.append(f"{DOC}: GENERATED supported-camera markers are missing")
    return out, problems


def _stale_generated(root: Path, keep: set[Path]) -> list[Path]:
    d = root / LINUX_DIR
    return [p.relative_to(root) for p in sorted(d.glob("*.dtsi"))
            if BANNER in p.read_text(encoding="utf-8") and p.relative_to(root) not in keep]


def main(argv: list[str] | None = None, root: Path = REPO) -> int:
    ap = argparse.ArgumentParser(description=__doc__.split("\n\n")[0])
    ap.add_argument("--check", action="store_true", help="verify committed outputs, write nothing")
    args = ap.parse_args(argv)
    out, problems = generate(root)
    stale = _stale_generated(root, set(out))
    drift = []
    for rel, text in out.items():
        p = root / rel
        cur = p.read_text(encoding="utf-8") if p.is_file() else None
        if cur != text:
            drift.append(rel)
            if not args.check:
                p.write_text(text, encoding="utf-8", newline="\n")
    for rel in stale:
        drift.append(rel)
        if not args.check:
            (root / rel).unlink()
    for pr in problems:
        print(f"gen_camera_dt: {pr}", file=sys.stderr)
    if args.check:
        for rel in drift:
            print(f"gen_camera_dt: {rel.as_posix()} is out of date; run python3 scripts/gen_camera_dt.py",
                  file=sys.stderr)
        return 1 if (drift or problems) else 0
    print(f"gen_camera_dt: {len(drift)} file(s) written, {len(problems)} problem(s)")
    return 1 if problems else 0


